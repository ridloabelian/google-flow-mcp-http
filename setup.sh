#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$REPO_ROOT"

DOMAIN=""
EMAIL=""
TUNNEL_TOKEN=""
NON_INTERACTIVE=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain)
      DOMAIN="$2"
      shift 2
      ;;
    --email)
      EMAIL="$2"
      shift 2
      ;;
    --tunnel-token)
      TUNNEL_TOKEN="$2"
      shift 2
      ;;
    --non-interactive|-y)
      NON_INTERACTIVE=true
      shift
      ;;
    *)
      echo "Unknown option: $1" >&2
      echo "Usage: ./setup.sh [--domain flow-mcp.domain.id] [--email akun@gmail.com] [--tunnel-token TOKEN] [--non-interactive]" >&2
      exit 1
      ;;
  esac
done

gen_hex_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    node -e "console.log(require('crypto').randomBytes(32).toString('hex'))"
  fi
}

if [[ "$NON_INTERACTIVE" == "false" && -z "$DOMAIN" ]]; then
  read -r -p "Masukkan domain publik MCP (kosongkan untuk lokal 127.0.0.1:3100): " DOMAIN || true
fi

if [[ "$NON_INTERACTIVE" == "false" && -z "$EMAIL" ]]; then
  read -r -p "Masukkan email Google Flow untuk proteksi akun (opsional, tekan Enter untuk skip): " EMAIL || true
fi

if [[ "$NON_INTERACTIVE" == "false" && -n "$DOMAIN" && -z "$TUNNEL_TOKEN" ]]; then
  read -r -p "Masukkan CLOUDFLARE_TUNNEL_TOKEN bila memakai Docker cloudflared (opsional): " TUNNEL_TOKEN || true
fi

CLEAN_DOMAIN="${DOMAIN#https://}"
CLEAN_DOMAIN="${CLEAN_DOMAIN#http://}"
CLEAN_DOMAIN="${CLEAN_DOMAIN%%/*}"

if [[ -n "$CLEAN_DOMAIN" ]]; then
  PUBLIC_BASE_URL="https://${CLEAN_DOMAIN}"
  ALLOWED_HOSTS="127.0.0.1,localhost,127.0.0.1:3100,localhost:3100,flow-mcp-server,flow-mcp-server:3100,${CLEAN_DOMAIN}"
else
  CLEAN_DOMAIN="127.0.0.1:3100"
  PUBLIC_BASE_URL="http://127.0.0.1:3100"
  ALLOWED_HOSTS="127.0.0.1,localhost,127.0.0.1:3100,localhost:3100,flow-mcp-server,flow-mcp-server:3100"
fi

if [[ -f .env ]]; then
  echo "[setup] File .env sudah ada, membaca token yang tersimpan..."
  AUTH_TOKEN="$(grep -E '^FLOW_MCP_AUTH_TOKEN=' .env | cut -d'=' -f2- || true)"
  SIGN_SECRET="$(grep -E '^FLOW_MEDIA_SIGNING_SECRET=' .env | cut -d'=' -f2- || true)"
  [[ -z "$AUTH_TOKEN" ]] && AUTH_TOKEN="$(gen_hex_secret)"
  [[ -z "$SIGN_SECRET" ]] && SIGN_SECRET="$(gen_hex_secret)"
else
  AUTH_TOKEN="$(gen_hex_secret)"
  SIGN_SECRET="$(gen_hex_secret)"

  cat > .env <<EOF
# Auto-generated by ./setup.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
HOST=0.0.0.0
PORT=3100
PUBLIC_BASE_URL=${PUBLIC_BASE_URL}

FLOW_MCP_AUTH_TOKEN=${AUTH_TOKEN}
FLOW_MEDIA_SIGNING_SECRET=${SIGN_SECRET}
FLOW_MEDIA_URL_TTL_SECONDS=3600

FLOW_ALLOWED_HOSTS=${ALLOWED_HOSTS}
FLOW_STATELESS_HTTP=false
FLOW_SESSION_TTL_MS=1800000

FLOW_CDP_URL=http://127.0.0.1:9222
FLOW_ALLOW_REMOTE_CDP=false
FLOW_BASE_URL=https://flow.google.com
FLOW_EXPECTED_EMAIL=${EMAIL}

FLOW_MAX_CREDITS_PER_CALL=25
FLOW_DAILY_CREDIT_CAP=200
FLOW_JOB_TIMEOUT_MS=360000
FLOW_POLL_INTERVAL_MS=5000
FLOW_ACTION_DELAY_MS=750
FLOW_OUTPUT_DIR=./exports
FLOW_STATE_DIR=./state
FLOW_SELECTORS_PATH=./config/selectors.map.json

CLOUDFLARE_TUNNEL_TOKEN=${TUNNEL_TOKEN}
EOF
  chmod 600 .env
  echo "[setup] Berhasil membuat .env dengan token acak 256-bit."
fi

mkdir -p exports state/jobs state/screenshots generated-configs

cat > generated-configs/mcp-client.json <<EOF
{
  "mcpServers": {
    "google-flow": {
      "type": "http",
      "url": "${PUBLIC_BASE_URL}/mcp",
      "headers": {
        "Authorization": "Bearer ${AUTH_TOKEN}"
      }
    }
  }
}
EOF
chmod 600 generated-configs/mcp-client.json

if [[ "$PUBLIC_BASE_URL" == https://* ]]; then
  sed "s/flow-mcp.domainkamu.id/${CLEAN_DOMAIN}/g" deploy/caddy/Caddyfile > generated-configs/Caddyfile
  sed "s/flow-mcp.domainkamu.id/${CLEAN_DOMAIN}/g" deploy/nginx/flow-mcp.conf > generated-configs/nginx-flow-mcp.conf
  sed "s/flow-mcp.domainkamu.id/${CLEAN_DOMAIN}/g" deploy/cloudflared/config.yml > generated-configs/cloudflared-config.yml
  sed "s/flow-mcp.domainkamu.id/${CLEAN_DOMAIN}/g" deploy/cloudflare-edge-rules.json > generated-configs/cloudflare-edge-rules.json
fi

echo ""
echo "=================================================================="
echo " Plug-and-Play Setup Selesai!"
echo "=================================================================="
echo " Endpoint MCP  : ${PUBLIC_BASE_URL}/mcp"
echo " Client Config : generated-configs/mcp-client.json"
echo ""
echo " Langkah selanjutnya:"
echo "   1) Docker Headless + KasmVNC : make up  (atau: make up-tunnel)"
echo "   2) Bare-Metal Lokal          : make install && make chrome && make start"
echo "   3) Uji End-to-End Smoke Test : make test"
echo "   4) Pasang SKILL.md ke Agent  : make install-skill"
echo "=================================================================="
